export let lang: "es" | "en" = typeof localStorage !== "undefined" && localStorage.getItem("lang") === "en" ? "en" : "es";

export function setLang(l: "es" | "en"): void {
  lang = l;
  if (typeof localStorage !== "undefined") localStorage.setItem("lang", l);
}

export function t(k: string): string {
  return I18N[lang][k] ?? k;
}
